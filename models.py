class Room:
    """
    Represents a classroom with a specified number of rows and columns.
    It includes an optional gap in seating arrangement and maintains a matrix representation.

    Attributes:
        rows (int): Number of rows in the room.
        columns (int): Number of columns in the room.
        gap (int, optional): Specifies after which column a gap should be inserted.
        type (int): A unique type identifier based on the number of created rooms.
        matrix (list[list[str]]): A 2D list representing the seating arrangement.
    """
    def __init__(self, rows, columns, gap=None):
        """
        Initializes a Room instance with the given dimensions and optional gap.

        Args:
            rows (int): The number of rows in the room.
            columns (int): The number of columns in the room.
            gap (int, optional): If specified, inserts an empty space after the specified column.
        
        The `matrix` is created as:
        - If `gap` is provided, it inserts an empty space (`"    "`) after `gap`th column.
        - Otherwise, it fills the room with `"______"` representing available seats.

        The `type` attribute is assigned a unique number based on the total number of rooms created.

        The created Room instance is added to the global `rooms` list.
        """
        self.rows = rows 
        self.columns = columns 
        self.gap = gap 
        self.type = len(rooms) + 1
        self.matrix = [["______"] * gap + ["    "] + ["______"] * (columns-gap) for _ in range(rows)] if (gap!=None) else [["______"] * columns for _ in range(rows)] # list[list]: list of lists depicting rows and columns (columns x rows filled with '_')
        rooms.append(self)
    
    def __str__(self):
        """
        Returns a string representation of the room's seating arrangement.

        Returns:
            str: A formatted string where each row is joined with spaces to represent the matrix.
        """
        return "\n".join(" ".join(row) for row in self.matrix)
    
class Branch():
    """
    Represents an Academic Branch with a specific year and student strength.

    Attributes:
        name (str): The name of the branch (e.g., "CS", "CC", "EE").
        year (str): The academic year (e.g., "24", "23", "25", f"YY").
        strength (int): The total number of students in the branch.
        identity (str): A unique identifier formed by concatenating `year` and `name`.
    """
    def __init__(self, name, year, strength):
        """
        Initializes a Branch instance with the given name, year, and student strength.

        Args:
            name (str): The branch name (e.g., "CS", "CC", "EE").
            year (str): The academic year (e.g., "24", "23", "25", "YY").
            strength (int): The total number of students in the branch.
        
        The `identity` attribute is generated by concatenating `year` and `name`
        to create a unique identifier for the branch.

        The instance is added to the global `branches` list.
        """
        self.name = name
        self.year = year
        self.strength = strength
        self.identity = year + name
        branches.append(self)

    def __str__(self):
        """
        Returns a string representation of the Branch instance.
        Returns:
            str: A formatted string displaying branch identity and student strength.
        """
        return f"Branch: {self.identity}\nStrength: {self.strength}\n"

class Exam():
    """
    Represents an exam with a specific code, date, time, and associated branches.

    Attributes:
        code (str): The unique code of the examination (e.g., "GMAT101").
        date (str): The date of the examination in "dd/mm/yy" format.
        time (str): The time of the examination in 24-hour format ("HH:MM").
        Branches (list[Branch]): A list of `Branch` objects associated with this exam.
    """
    def __init__(self, code, date, time, Branches):
        """
        Initializes an Exam instance with the given details.

        Args:
            code (str): The exam code (e.g., "GMAT101").
            date (str): The exam date in "dd/mm/yy" format.
            time (str): The exam time in 24-hour format ("HH:MM").
            Branches (list[Branch]): A list of `Branch` objects associated with this exam.

        The instance is added to the global `exams` list.
        """
        self.code = code 
        self.date = date 
        self.time = time
        self.Branches = Branches 
        exams.append(self)
    
    def __str__(self):
        """
        Returns a string representation of the Exam instance.

        Returns:
            str: A formatted string displaying the exam details.
        """
        return f"Code: {self.code}\nDate: {self.date}\nTime: {self.time}\nBranches: {self.Branches}"
    
